export type Lang = 'en' | 'fr'
export const LANG_KEY = 'herdrLanguage'

function readLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY)
    if (saved === 'fr' || saved === 'en') return saved
    return navigator.languages?.some(l => l.toLowerCase().startsWith('fr')) ? 'fr' : 'en'
  }
  catch { return 'en' }
}

// Changer de langue recharge l'app (comme avant) : pas besoin de réactivité.
export const language: Lang = import.meta.client ? readLang() : 'en'

export function t(french: string): string {
  return language === 'en' ? (EN[french] || french) : french
}

// Phrase avec des parties variables : les deux versions écrites en entier.
export function tl(fr: string, en: string): string {
  return language === 'en' ? en : fr
}

export function setLanguage(l: Lang) {
  try { localStorage.setItem(LANG_KEY, l) }
  catch { /* stockage indisponible */ }
}
